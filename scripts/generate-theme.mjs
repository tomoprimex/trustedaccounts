// Generates src/app/theme.css — the light/dark color tokens behind every Tailwind color class.
// Run: node scripts/generate-theme.mjs   (re-run after changing palettes below)
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const twColors = require("tailwindcss/colors");

export const HUES = [
  "blue", "green", "red", "purple", "amber", "emerald", "yellow", "orange",
  "pink", "indigo", "cyan", "teal", "rose", "sky", "violet", "lime", "fuchsia",
];
export const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];

// Brand blue built around #1e65f3.
const brandBlue = {
  50: "#eff5ff", 100: "#dbe8fe", 200: "#bfd5fe", 300: "#93b8fd", 400: "#6095fa",
  500: "#3b7bf6", 600: "#1e65f3", 700: "#1650d6", 800: "#1842ad", 900: "#193b88", 950: "#142653",
};

// Neutrals: light uses Tailwind slate; dark is a hand-tuned navy-tinted inversion.
const slateLight = twColors.slate;
const slateDark = {
  50: "#131e33", 100: "#19253d", 200: "#24324d", 300: "#334360", 400: "#6b7a94",
  500: "#8b9ab2", 600: "#a9b6ca", 700: "#c4cedd", 800: "#dde4ee", 900: "#eef2f7", 950: "#f8fafc",
};

const palette = (name) => (name === "blue" ? brandBlue : twColors[name]);

const rgb = (hex) => {
  const h = hex.replace("#", "");
  const n = parseInt(h.length === 3 ? h.split("").map((c) => c + c).join("") : h, 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

// In dark mode, pale tints become deep tints and deep shades become pale ones,
// while mid-tones (300–700) keep their identity so buttons stay on-brand.
const DARK_SWAP = { 50: "950", 100: "900", 200: "800", 800: "200", 900: "100", 950: "50" };
// Text gets an extra lift so coloured text stays readable on dark surfaces.
const DARK_TEXT_SWAP = { ...DARK_SWAP, 600: "400", 700: "300" };

let light = "";
let dark = "";

for (const s of SHADES) {
  light += `  --slate-${s}: ${rgb(slateLight[s])};\n`;
  dark += `  --slate-${s}: ${rgb(slateDark[s])};\n`;
}

for (const hue of HUES) {
  const p = palette(hue);
  for (const s of SHADES) {
    light += `  --${hue}-${s}: ${rgb(p[s])};\n  --tx-${hue}-${s}: ${rgb(p[s])};\n`;
    dark += `  --${hue}-${s}: ${rgb(p[DARK_SWAP[s] ?? s])};\n`;
    dark += `  --tx-${hue}-${s}: ${rgb(p[DARK_TEXT_SWAP[s] ?? s])};\n`;
  }
}

const css = `/* AUTO-GENERATED by scripts/generate-theme.mjs — do not edit by hand. */
:root {
  color-scheme: light;
  --canvas: ${rgb("#f5f7fb")};
  --surface: ${rgb("#ffffff")};
  --white-surface: ${rgb("#ffffff")};
${light}}

.dark {
  color-scheme: dark;
  --canvas: ${rgb("#0a1222")};
  --surface: ${rgb("#0f192c")};
  --white-surface: ${rgb("#0f192c")};
${dark}}
`;

writeFileSync(new URL("../src/app/theme.css", import.meta.url), css);
console.log("wrote src/app/theme.css");
